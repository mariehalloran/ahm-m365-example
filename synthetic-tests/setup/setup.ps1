#Requires -Version 7.4
#Requires -Modules ExchangeOnlineManagement
<#
.SYNOPSIS
    Sets up the Microsoft 365 side of monitoring.config.json: mailbox access, team members,
    channels, reply-mail seeds, and the IDs that deploy needs but the config does not hold.

.DESCRIPTION
    Run it after editing the root monitoring.config.json and before `npm run deploy`:

        az login        # as an Exchange and Teams administrator of the Microsoft 365 tenant
        npm run setup   # from synthetic-tests/; `npm run setup -- -Plan` only reports what it would change

    It only adds what is missing, so running it again is safe. It needs the foundation's environment to exist
    (the calling callback URL is looked up from it); on a new foundation run `npm run deploy` once with
    `deployment.stage: "foundation"` first.

      1. Exchange  extends the worker's management scope to every configured mailbox
      2. Teams     adds each group's accounts to the team and finds or creates the channel named by `channelName`
      3. Lookups   finds the IDs the config leaves out: the peer bot's client ID, the calling callback URL, the
                   meeting organizer's and each OneDrive account's user ID
      4. Exchange  validates or provisions a retained received self-addressed SELF-REPLY fixture per mailbox

    The config names things (a resource by its name, an account by its address); every ID found or created here is
    written to the .env file next to the config, never into the config. `npm run deploy` reads both. Each line is
    <TENANT>__<TARGET>__<FIELD>=value, for example CONSTO__TEAMS_PROBE_002__CHANNEL_ID.
#>
param(
    [string]$Config = (Join-Path $PSScriptRoot '../../monitoring.config.json'),
    [switch]$Plan,
    [switch]$ReprovisionReplySeeds
)

$ErrorActionPreference = 'Stop'
$PSNativeCommandUseErrorActionPreference = $true

$Config = (Resolve-Path $Config).Path
$EnvFile = Join-Path (Split-Path $Config) '.env'
$document = Get-Content $Config -Raw | ConvertFrom-Json -Depth 100
foreach ($configuredTenant in $document.tenants) {
    $configured = $configuredTenant.services.exchange
    if ($configured.targets | Where-Object { $_.PSObject.Properties.Name -contains 'recipientMailbox' -or $_.PSObject.Properties.Name -contains 'distributionList' }) {
        throw 'Obsolete Exchange pair/distribution targets. Configure one { id, mailbox } target per unique user before running setup.'
    }
    if ($configured.scenarios.PSObject.Properties.Name | Where-Object { $_ -in @('distribution-list-mail', 'meeting-invitation') }) {
        throw 'Removed Exchange journeys are not supported. Select only the five single-user scenarios.'
    }
}

# The signed-in administrator decides which tenant of the config is set up (run once per tenant).
$account = az account show | ConvertFrom-Json
$tenant = $document.tenants | Where-Object { $_.tenantId -eq $account.tenantId }
if (-not $tenant) {
    throw "Signed in to tenant $($account.tenantId), which monitoring.config.json does not list. Run: az login --tenant <tenantId>"
}
Write-Host "Tenant '$($tenant.id)', signed in as $($account.user.name)$($Plan ? ' (-Plan: nothing will change)' : '')"

# Every change goes through here: a plan only reports it.
function Confirm-Change([string]$Description) {
    if ($Plan) { Write-Host "  would $Description" }
    -not $Plan
}

# ---- Generated IDs: .env, one KEY=value per line -------------------------------------------------------------------

function Read-Bindings {
    $values = @{}
    if (Test-Path $EnvFile) {
        foreach ($line in Get-Content $EnvFile) {
            if ($line -match '^([A-Z0-9_]+)=(.*)$') { $values[$Matches[1]] = $Matches[2] }
        }
    }
    $values
}

function Get-BindingKey([string]$TargetId, [string]$Field) {
    $part = { param($text) $text.ToUpperInvariant() -replace '[^A-Z0-9]', '_' }
    "$(& $part $tenant.id)__$(& $part $TargetId)__$Field"
}

function Set-Binding([string]$Key, [string]$Value) {
    if ($bindings[$Key] -eq $Value) { return }
    if (-not (Confirm-Change "write $Key to $EnvFile")) { return }
    $lines = (Test-Path $EnvFile) ? @(Get-Content $EnvFile) : @('# Generated by npm run setup and the setup commands; safe to delete and regenerate. Not for secrets.')
    $temporary = "$EnvFile.tmp"
    (@($lines | Where-Object { -not $_.StartsWith("$Key=") }) + "$Key=$Value") | Set-Content $temporary
    if (-not $IsWindows) { chmod 600 $temporary }
    Move-Item $temporary $EnvFile -Force
    $bindings[$Key] = $Value
    Write-Host "  wrote $Key"
}

$bindings = Read-Bindings

# ---- Microsoft Graph as the signed-in administrator ----------------------------------------------------------------

function Invoke-Graph([string]$Method, [string]$Path, $Body) {
    $request = @{
        Method = $Method; ContentType = 'application/json'; Headers = $graphHeaders
        Uri = $Path.StartsWith('https://') ? $Path : "https://graph.microsoft.com/v1.0$Path"
    }
    if ($Body) { $request.Body = $Body | ConvertTo-Json -Depth 5 }
    try { Invoke-RestMethod @request }
    catch { throw "$Method $Path failed: $($_.ErrorDetails.Message ?? $_.Exception.Message)" }
}

function Get-GraphList([string]$Path) {
    while ($Path) {
        $page = Invoke-Graph GET $Path
        $page.value
        $Path = $page.'@odata.nextLink'
    }
}

# ---- Azure resources are named in the config -----------------------------------------------------------------------

# A bare name is a resource in the health model's resource group; a value that starts with / is a full resource ID.
function Resolve-ResourceId([string]$Value, [string]$Provider, [string]$Type) {
    if ($Value.StartsWith('/')) { return $Value }
    "/subscriptions/$($document.healthModel.subscriptionId)/resourceGroups/$($document.healthModel.resourceGroup)/providers/$Provider/$Type/$Value"
}

$foundation = $document.deployment.foundation
$registry = $foundation.mode -eq 'existing' ? $foundation.registry.Split('/')[-1] : $foundation.registryName
$environmentId = Resolve-ResourceId ($foundation.mode -eq 'existing' ? $foundation.environment : $foundation.environmentName) 'Microsoft.App' 'managedEnvironments'

# ---- Exchange ------------------------------------------------------------------------------------------------------

$exchange = $tenant.services.exchange
if ($exchange.enabled -ne $false -and $exchange.execution.mode -eq 'live') {
    Write-Host 'Exchange'
    if (-not $exchange.worker.identity) { throw 'Set tenants[].services.exchange.worker.identity to the name of the Exchange worker''s managed identity.' }
    $workerIdentity = Resolve-ResourceId $exchange.worker.identity 'Microsoft.ManagedIdentity' 'userAssignedIdentities'
    if ($document.deployment.azureTenantId -and $document.deployment.azureTenantId -ne $tenant.tenantId) {
        throw "The Exchange worker identity lives in tenant $($document.deployment.azureTenantId), not $($tenant.tenantId). Extend its access by hand: docs/cross-tenant-access.md"
    }
    $token = az account get-access-token --resource https://outlook.office365.com --query accessToken -o tsv
    Connect-ExchangeOnline -AccessToken $token -UserPrincipalName $account.user.name -ShowBanner:$false

    try {
        # Every mailbox the journeys touch, mapped from the address in the config to its primary SMTP address.
        $primary = @{}
        $addresses = $exchange.targets.mailbox | Where-Object { $_ } | Sort-Object -Unique
        foreach ($address in $addresses) {
            $mailbox = Get-Mailbox -Identity $address -ErrorAction SilentlyContinue
            if (-not $mailbox) { throw "$address has no Exchange mailbox. Assign the account an Exchange Online license first." }
            if ($mailbox.PrimarySmtpAddress -match "['()\s]") { throw "$address cannot be added to a management scope filter (it contains a quote, parenthesis or space)." }
            $primary[$address] = $mailbox.PrimarySmtpAddress
        }

        # 1. The worker identity reaches mailboxes only through its management scope: add the missing ones, never remove.
        $identity = az identity show --ids $workerIdentity | ConvertFrom-Json
        $scopes = @(Get-ManagementRoleAssignment -RoleAssignee $identity.principalId | Where-Object CustomResourceScope |
            ForEach-Object CustomResourceScope | Sort-Object -Unique)
        if ($scopes.Count -ne 1) {
            throw "Expected the worker identity's Exchange roles on exactly one management scope but found $($scopes.Count). Approve its access first: MAILBOX-SYNTHETIC-ACCESS.md, section 4."
        }
        $scope = Get-ManagementScope -Identity $scopes[0]
        $clause = "PrimarySmtpAddress -eq '([^']+)'"
        if ($scope.RecipientFilter -replace $clause -replace '[()\s]|-or') {
            throw "Scope $($scope.Name) has a recipient filter other than PrimarySmtpAddress clauses. Add the mailboxes to it by hand."
        }
        $inScope = @([regex]::Matches($scope.RecipientFilter, $clause) | ForEach-Object { $_.Groups[1].Value })
        $missing = @($primary.Values | Where-Object { $_ -notin $inScope } | Sort-Object -Unique)
        if ($missing -and (Confirm-Change "add $($missing -join ', ') to scope $($scope.Name)")) {
            $filter = (@($inScope + $missing | Sort-Object -Unique) | ForEach-Object { "(PrimarySmtpAddress -eq '$_')" }) -join ' -or '
            Set-ManagementScope -Identity $scope.Name -RecipientRestrictionFilter $filter
            Write-Host "  added $($missing.Count) mailbox(es) to scope $($scope.Name)"
        }

        # Exchange's own check sees a scope change at once. The live worker identity can lag behind it, because Exchange
        # caches application permissions for 30 minutes to 2 hours; the seed step below waits that out.
        $blocked = @($primary.Values | Sort-Object -Unique | Where-Object {
            Test-ServicePrincipalAuthorization -Identity $identity.principalId -Resource $_ |
                Where-Object { $_.AllowedResourceScope -eq $scope.Name -and $_.InScope -ne 'True' }
        })
        if ($blocked -and -not $Plan) { throw "Exchange reports these mailboxes out of scope: $($blocked -join ', ')" }
        Write-Host ($blocked ? "  not in scope yet: $($blocked -join ', ')" : '  every mailbox is in the worker''s scope')

    }
    finally { Disconnect-ExchangeOnline -Confirm:$false }
}

# ---- Teams ---------------------------------------------------------------------------------------------------------

$graphHeaders = @{ Authorization = 'Bearer ' + (az account get-access-token --resource-type ms-graph --query accessToken -o tsv) }

$teams = $tenant.services.teams
if ($teams.enabled -ne $false -and $teams.execution.mode -eq 'live') {
    Write-Host 'Teams'
    $tenantAccounts = @($exchange.targets.mailbox) + @($tenant.services.onedrive.targets.userPrincipalName)

    foreach ($target in $teams.targets) {
        # The accounts of every group that lists this target must be members of its team.
        $wanted = $document.groups | Where-Object { $target.id -in $_.teams } | ForEach-Object { $_.accounts } |
            Where-Object { $_ -in $tenantAccounts } | Sort-Object -Unique
        $memberIds = @(Get-GraphList "/groups/$($target.teamId)/members?`$select=id" | ForEach-Object id)
        foreach ($upn in $wanted) {
            $user = Invoke-Graph GET "/users/$upn`?`$select=id"
            if ($user.id -notin $memberIds -and (Confirm-Change "add $upn to team $($target.teamId)")) {
                Invoke-Graph POST "/groups/$($target.teamId)/members/`$ref" @{ '@odata.id' = "https://graph.microsoft.com/v1.0/directoryObjects/$($user.id)" } | Out-Null
                Write-Host "  added $upn to team $($target.teamId)"
            }
        }

        # The channel is found by name (created when missing); its ID goes to .env.
        if ($target.channelName) {
            $channel = Get-GraphList "/teams/$($target.teamId)/channels?`$select=id,displayName" | Where-Object displayName -eq $target.channelName
            if (-not $channel -and (Confirm-Change "create channel '$($target.channelName)' in team $($target.teamId)")) {
                $channel = Invoke-Graph POST "/teams/$($target.teamId)/channels" @{
                    displayName = $target.channelName; description = 'Synthetic monitoring'; membershipType = 'standard'
                }
                Write-Host "  created channel '$($target.channelName)'"
            }
            if ($channel) { Set-Binding (Get-BindingKey $target.id 'CHANNEL_ID') $channel.id }
        }
    }

    # IDs the config leaves out because they can be looked up: the peer bot's client ID (its managed identity's),
    # the calling callback URL (the Teams app's address in its environment) and the meeting organizer's user ID.
    if ($teams.access.peerIdentity) {
        $peer = az identity show --ids (Resolve-ResourceId $teams.access.peerIdentity 'Microsoft.ManagedIdentity' 'userAssignedIdentities') | ConvertFrom-Json
        Set-Binding (Get-BindingKey 'teams' 'BOT_PEER_CLIENT_ID') $peer.clientId
    }
    if ($teams.scenarios.'scheduled-meeting' -ne $false) {
        $environment = $environmentId.Split('/')
        $domain = az containerapp env show --name $environment[-1] --resource-group $environment[4] --subscription $environment[2] --query properties.defaultDomain -o tsv --only-show-errors
        Set-Binding (Get-BindingKey 'teams' 'CALLING_CALLBACK_URL') "https://$($teams.worker.appName).$domain/api/calls"
        foreach ($call in $teams.callTargets | Where-Object organizer) {
            Set-Binding (Get-BindingKey $call.id 'ORGANIZER_USER_ID') (Invoke-Graph GET "/users/$($call.organizer)`?`$select=id").id
        }
    }
}

# ---- OneDrive ------------------------------------------------------------------------------------------------------
# The drive and folder need a separately approved credential (npm run onedrive:setup); each account's user ID can be
# looked up here.

$onedrive = $tenant.services.onedrive
if ($onedrive.enabled -ne $false -and $onedrive.execution.mode -eq 'live') {
    Write-Host 'OneDrive'
    foreach ($target in $onedrive.targets) {
        Set-Binding (Get-BindingKey $target.id 'USER_ID') (Invoke-Graph GET "/users/$($target.userPrincipalName)`?`$select=id").id
    }
}

# ---- Reply-mail seeds ----------------------------------------------------------------------------------------------
# The reply journey answers a retained message that only the worker's own identity can create, so the worker's
# seed command runs once in a temporary Container Apps job. The job image is built from this checkout, so the
# code that provisions always matches the config.

# A target has its seed when the config or .env holds both halves of it.
function Test-ReplySeed($Target) {
    $Target.replySeed -or ($bindings[(Get-BindingKey $Target.id 'REPLY_SEED_MESSAGE_ID')] -and $bindings[(Get-BindingKey $Target.id 'REPLY_SEED_CORRELATION_ID')])
}

function New-ReplySeeds {
    $subscription = $document.healthModel.subscriptionId
    $resourceGroup = $document.healthModel.resourceGroup
    $identity = az identity show --ids $workerIdentity | ConvertFrom-Json

    $image = $document.deployment.image.reference
    if ($document.deployment.image.mode -eq 'build') {
        Write-Host '  building the worker image in ACR (about 90 seconds)'
        $repository = $document.deployment.image.repository
        $build = & {
            $PSNativeCommandUseErrorActionPreference = $false
            az acr build --registry $registry --subscription $subscription --image "${repository}:setup" --platform linux/amd64 `
                --file Dockerfile (Join-Path $PSScriptRoot '..') 2>&1
        }
        if ($LASTEXITCODE) { $build | Select-Object -Last 25; throw 'The worker image build failed.' }
        $image = "$(az acr show --name $registry --subscription $subscription --query loginServer -o tsv)/${repository}:setup"
    }

    # A permission failure (HTTP 403) right after the scope change is Exchange's permission cache catching up, so the
    # command is retried, every 2 minutes for up to 2.3 hours, only while every failure is of that kind. The seeds go
    # out as base64 text in a few long lines, because job logs show at most 300 lines.
    $script = @'
umask 077
mkdir -p .setup-seeds
echo "$CONFIG_B64" | base64 -d > .setup-seeds/monitoring.config.json
echo "$ENV_B64" | base64 -d > .setup-seeds/.env
set -- --config .setup-seeds/monitoring.config.json --tenant "$TENANT" --apply --setup-only
if [ "$REPROVISION_SEEDS" = true ]; then set -- "$@" --reprovision-seeds; fi
status=1
for attempt in $(seq 1 70); do
  node dist/exchange/src/mail-test-command.js "$@" > .setup-seeds/seed.log 2>&1
  status=$?
  cat .setup-seeds/seed.log
  [ $status -eq 0 ] && break
  grep setup-failed .setup-seeds/seed.log | grep -vq permission-failure && break
  grep -q permission-failure .setup-seeds/seed.log || break
  echo "SEED_RETRY $attempt"
  sleep 120
done
grep '__REPLY_SEED_' .setup-seeds/.env | base64 | tr -d '\n' | fold -w 4000 | sed 's/^/SEED_DATA /'
echo
echo "SEED_DONE $status"
sleep 120
'@
    $encode = { param($text) [Convert]::ToBase64String([Text.Encoding]::UTF8.GetBytes($text)) }
    $job = @{
        location = $document.deployment.location
        identity = @{ type = 'UserAssigned'; userAssignedIdentities = @{ $workerIdentity = @{} } }
        properties = @{
            environmentId = $environmentId
            configuration = @{
                triggerType = 'Manual'; replicaTimeout = 9000; replicaRetryLimit = 0
                manualTriggerConfig = @{ replicaCompletionCount = 1; parallelism = 1 }
                registries = @(@{ server = $image.Split('/')[0]; identity = $workerIdentity })
            }
            template = @{ containers = @(@{
                name = 'seed'; image = $image; resources = @{ cpu = 0.25; memory = '0.5Gi' }
                command = @('/bin/sh', '-c'); args = @($script)
                env = @(
                    @{ name = 'CONFIG_B64'; value = & $encode (Get-Content $Config -Raw) }
                    @{ name = 'ENV_B64'; value = & $encode ((Test-Path $EnvFile) ? (Get-Content $EnvFile -Raw) : '# none') }
                    @{ name = 'TENANT'; value = $tenant.id }
                    @{ name = 'REPROVISION_SEEDS'; value = "$ReprovisionReplySeeds".ToLowerInvariant() }
                    @{ name = 'AZURE_CLIENT_ID'; value = $identity.clientId }
                    @{ name = 'AZURE_TENANT_ID'; value = $tenant.tenantId }
                    @{ name = 'ENABLE_LIVE_M365'; value = 'true' }
                    @{ name = 'ENABLE_BETA_SERVICE_ACTIVITY'; value = "$($document.deployment.enableBetaServiceActivity)".ToLowerInvariant() }
                )
            }) }
        }
    }

    $name = "m365-setup-seeds-$(Get-Date -Format 'MMddHHmmss')"
    $definition = Join-Path (Split-Path $Config) ".$name.json"
    if (Test-Path $definition) { throw "Setup job definition already exists: $definition" }
    $target = @('--name', $name, '--resource-group', $resourceGroup, '--subscription', $subscription)
    try {
        $job | ConvertTo-Json -Depth 10 | Set-Content $definition
        Write-Host "  starting job $name"
        az containerapp job create @target --yaml $definition --only-show-errors | Out-Null
        az containerapp job start @target --only-show-errors | Out-Null

        # The job prints its result and then sleeps, because job logs can only be read while its replica runs.
        $logs = ''
        $retries = 0
        for ($attempt = 1; $attempt -le 900 -and $logs -notmatch 'SEED_DONE'; $attempt++) {
            Start-Sleep -Seconds 10
            # A job that has only just started has no execution or replica yet: that is not an error, keep polling.
            $status = try { az containerapp job execution list @target --query '[0].properties.status' -o tsv --only-show-errors 2>$null } catch { '' }
            $logs = try { (az containerapp job logs show @target --container seed --format text --tail 300 --only-show-errors 2>$null) -join "`n" } catch { '' }
            if ($status -eq 'Failed') { throw "The seed job failed to run: $logs" }
            $latest = [regex]::Matches($logs, 'SEED_RETRY (\d+)') | ForEach-Object { [int]$_.Groups[1].Value } | Measure-Object -Maximum
            if ($latest.Maximum -gt $retries) {
                $retries = $latest.Maximum
                Write-Host "  Exchange has not applied the new mailbox permissions yet (it caches them for 30 minutes to 2 hours); retry $retries"
            }
        }
        $done = [regex]::Match($logs, 'SEED_DONE (\d+)')
        $tail = ($logs -split "`n" | Select-Object -Last 25) -join "`n"
        if (-not $done.Success) { throw "The seed job did not finish in 2.5 hours. Last output:`n$tail" }
        $data = ([regex]::Matches($logs, 'SEED_DATA ([A-Za-z0-9+/=]+)') | ForEach-Object { $_.Groups[1].Value }) -join ''
        foreach ($line in [Text.Encoding]::UTF8.GetString([Convert]::FromBase64String($data)) -split "`n") {
            if ($line -match '^([A-Z0-9_]+__REPLY_SEED_[A-Z_]+)=(\S+)$') { Set-Binding $Matches[1] $Matches[2] }
        }
        $without = @($pending | Where-Object { -not (Test-ReplySeed $_) })
        if ($without -or $done.Groups[1].Value -ne '0') {
            throw "Reply seeds failed for $($without.id -join ', ') (exit $($done.Groups[1].Value)). Last output:`n$tail"
        }
    }
    finally {
        az containerapp job delete @target --yes --only-show-errors 2>$null | Out-Null
        Remove-Item $definition -ErrorAction SilentlyContinue
    }
}

if ($exchange.enabled -ne $false -and $exchange.execution.mode -eq 'live' -and $exchange.scenarios.'reply-mail' -ne $false) {
    $pending = @($exchange.targets)
    Write-Host 'Reply seeds'
    if (Confirm-Change "validate or provision retained received SELF-REPLY seeds for $($pending.id -join ', ') in a one-time job") { New-ReplySeeds }
}

Write-Host ($Plan ? 'Nothing was changed.' : 'Setup finished. Next: npm run deploy')
