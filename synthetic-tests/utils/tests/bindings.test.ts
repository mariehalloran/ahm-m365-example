function setAt(document: unknown, location: string, path: string, value: string): void {
  const names = [...location.split("."), ...path.split(".")];
  const field = names.pop()!;
  names.reduce<Record<string, any>>((holder, name) => holder[name], document as Record<string, any>)[field] = value;
}

async function workspace(document: unknown = configFixture()) {
  const directory = await mkdtemp(join(tmpdir(), "ahm-bindings-"));
  directories.push(directory);
  const file = join(directory, "monitoring.config.json");
  await writeFile(file, JSON.stringify(document));
  return { directory, file, env: join(directory, ".env") };
}

const envText = (entries: Record<string, string>) => `${Object.entries(entries).map(([key, value]) => `${key}=${value}`).join("\n")}\n`;
const listing = async (directory: string) => (await readdir(directory)).sort();

function failure(run: () => unknown): Error {
  try { run(); }
  catch (error) { return error as Error; }
  throw new Error("Expected the call to throw");
}

