describe("saveBindings", () => {
  it("creates a private .env next to the config with a header comment that reads back exactly", async () => {
    const { directory, file, env } = await workspace();
    await saveBindings(file, bindings);
    expect(await readFile(env, "utf8")).toBe(`${header}\n${envText(bindings)}`);
    expect(await readBindings(file)).toEqual(bindings);
    expect((await stat(env)).mode & 0o777).toBe(0o600);
    expect(await listing(directory)).toEqual([".env", "monitoring.config.json"]);
  });

  it("replaces existing keys in place, appends new ones and keeps every other line", async () => {
    const { file, env } = await workspace();
    await writeFile(env, "# my notes\nKEEP_ME=1\nCONSTO__A__DRIVE_ID=old\n\n# trailing\nexport OTHER=2\nCONSTO__B__DRIVE_ID=untouched\n");
    await saveBindings(file, { CONSTO__A__DRIVE_ID: "new", CONSTO__A__FOLDER_ID: "folder" });
    expect(await readFile(env, "utf8")).toBe(
      "# my notes\nKEEP_ME=1\nCONSTO__A__DRIVE_ID=new\n\n# trailing\nexport OTHER=2\nCONSTO__B__DRIVE_ID=untouched\nCONSTO__A__FOLDER_ID=folder\n",
    );
  });

  it("keeps the line endings of the existing file and does not add a header to it", async () => {
    const { file, env } = await workspace();
    await writeFile(env, "KEEP_ME=1\r\nCONSTO__A__DRIVE_ID=old\r\n");
    await saveBindings(file, { CONSTO__A__DRIVE_ID: "new", CONSTO__A__FOLDER_ID: "folder" });
    expect(await readFile(env, "utf8")).toBe("KEEP_ME=1\r\nCONSTO__A__DRIVE_ID=new\r\nCONSTO__A__FOLDER_ID=folder\r\n");
  });

  it("appends after a last line without a line ending and treats an empty file like a missing one", async () => {
    const { file, env } = await workspace();
    await writeFile(env, "# none");
    await saveBindings(file, { KEY_ONE: "1" });
    expect(await readFile(env, "utf8")).toBe("# none\nKEY_ONE=1\n");
    await writeFile(env, "");
    await saveBindings(file, { KEY_ONE: "1" });
    expect(await readFile(env, "utf8")).toBe(`${header}\nKEY_ONE=1\n`);
  });

  it("is idempotent and does not rewrite a file that already holds the entries", async () => {
    const { file, env } = await workspace();
    await saveBindings(file, bindings);
    const first = await stat(env);
    const text = await readFile(env, "utf8");
    await saveBindings(file, bindings);
    await saveBindings(file, { CONTOSO__TEAMS_PROBE_001__CHANNEL_ID: channelId });
    const second = await stat(env);
    expect(await readFile(env, "utf8")).toBe(text);
    expect([second.ino, second.mtimeMs]).toEqual([first.ino, first.mtimeMs]);
  });

  it("replaces the file atomically through a temporary file and leaves none behind", async () => {
    const { directory, file, env } = await workspace();
    await saveBindings(file, { KEY_ONE: "1" });
    const reader = await open(env, "r");
    try {
      await saveBindings(file, { KEY_ONE: "2" });
      expect(await reader.readFile("utf8")).toBe(`${header}\nKEY_ONE=1\n`);
      expect(await readFile(env, "utf8")).toBe(`${header}\nKEY_ONE=2\n`);
    } finally {
      await reader.close();
    }
    expect(await listing(directory)).toEqual([".env", "monitoring.config.json"]);
  });

  it("makes a file that was more open private again", async () => {
    const { file, env } = await workspace();
    await writeFile(env, "KEEP_ME=1\n");
    await chmod(env, 0o644);
    await saveBindings(file, { KEY_ONE: "1" });
    expect((await stat(env)).mode & 0o777).toBe(0o600);
  });

  it("writes nothing when there are no entries", async () => {
    const { directory, file } = await workspace();
    await saveBindings(file, {});
    expect(await listing(directory)).toEqual(["monitoring.config.json"]);
  });

  it.each(["", "two words", "tab\tseparated", 'say"hi', "it's", "back`tick", "a#b", "new\nline"])(
    "rejects the unsafe value %j before touching the file", async value => {
      const { directory, file, env } = await workspace();
      await expect(saveBindings(file, { KEY_ONE: "1", KEY_TWO: value })).rejects.toThrow(ConfigurationError);
      expect(await listing(directory)).toEqual(["monitoring.config.json"]);
      await writeFile(env, "KEEP_ME=1\n");
      await expect(saveBindings(file, { KEY_TWO: value })).rejects.toThrow("KEY_TWO");
      expect(await readFile(env, "utf8")).toBe("KEEP_ME=1\n");
      expect(await listing(directory)).toEqual([".env", "monitoring.config.json"]);
    },
  );

  it.each(["", "lower", "WITH-DASH", "WITH SPACE", "A=B"])("rejects the unsafe key %j", async key => {
    const { directory, file } = await workspace();
    await expect(saveBindings(file, { [key]: "1" })).rejects.toThrow("Binding keys");
    expect(await listing(directory)).toEqual(["monitoring.config.json"]);
  });

  it("keeps every entry when saves to one file overlap", async () => {
    const { file, env } = await workspace();
    const entries = Array.from({ length: 40 }, (_, index) => [`KEY_${index}`, String(index)] as const);
    await Promise.all(entries.map(([key, value]) => saveBindings(file, { [key]: value })));
    expect(await readBindings(file)).toEqual(Object.fromEntries(entries));
    expect((await readFile(env, "utf8")).split("\n").filter(line => line === header)).toHaveLength(1);
  });

  it("lets later saves run after one failed", async () => {
    const { file } = await workspace();
    const rejected = saveBindings(file, { KEY_ONE: "two words" });
    const saved = saveBindings(file, { KEY_TWO: "2" });
    await expect(rejected).rejects.toThrow(ConfigurationError);
    await saved;
    expect(await readBindings(file)).toEqual({ KEY_TWO: "2" });
  });
});

